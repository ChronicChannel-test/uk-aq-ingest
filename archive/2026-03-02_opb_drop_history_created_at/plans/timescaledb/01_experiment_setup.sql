-- TimescaleDB storage assessment experiment setup
-- Writes only to staging schema.
-- Run with:
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f plans/timescaledb/01_experiment_setup.sql

begin;

create extension if not exists timescaledb with schema extensions;
create schema if not exists staging;

-- Keep experiment parameters in one table for deterministic reruns.
create table if not exists staging.timescaledb_experiment_config (
  id bigint generated by default as identity primary key,
  sample_strategy text not null default 'single_station_90_days',
  source_schema text not null default 'uk_aq_history',
  source_table text not null default 'observations',
  sample_station_id bigint,
  sample_timeseries_id integer,
  sample_days integer not null default 90,
  inserted_at timestamptz not null default now()
);

-- Raw sample table mirrors the source shape (adjust column list if your source differs).
create table if not exists staging.obs_sample_raw (
  connector_id integer not null,
  timeseries_id integer not null,
  observed_at timestamptz not null,
  value double precision,
  status text,
  created_at timestamptz,
  primary key (connector_id, timeseries_id, observed_at)
);

create index if not exists obs_sample_raw_observed_at_idx
  on staging.obs_sample_raw (observed_at desc);
create index if not exists obs_sample_raw_timeseries_observed_idx
  on staging.obs_sample_raw (timeseries_id, observed_at desc);

-- Destination table for Timescale test. It starts as a regular table.
create table if not exists staging.obs_sample_ts (
  connector_id integer not null,
  timeseries_id integer not null,
  observed_at timestamptz not null,
  value double precision,
  status text,
  created_at timestamptz
);

-- Representative indexes similar to observation query patterns.
create unique index if not exists obs_sample_ts_pk_like_idx
  on staging.obs_sample_ts (connector_id, timeseries_id, observed_at);
create index if not exists obs_sample_ts_observed_at_idx
  on staging.obs_sample_ts (observed_at desc);
create index if not exists obs_sample_ts_timeseries_observed_idx
  on staging.obs_sample_ts (timeseries_id, observed_at desc);

commit;
