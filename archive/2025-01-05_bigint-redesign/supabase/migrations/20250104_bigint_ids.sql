-- Migration: switch to bigint internal IDs for stations/timeseries/observations.
-- Run this once after applying the updated schema.

-- 1) Stations: rename text id -> source_id, add bigint id
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_name = 'stations' and column_name = 'id' and data_type = 'text'
  ) then
    execute 'alter table stations rename column id to source_id';
  end if;
  if not exists (
    select 1 from information_schema.columns
    where table_name = 'stations' and column_name = 'id'
  ) then
    execute 'alter table stations add column id bigint generated by default as identity';
  end if;
end $$;
alter table stations alter column source_id set not null;
alter table stations drop constraint if exists stations_pkey;
alter table stations add constraint stations_pkey primary key (id);
alter table stations drop constraint if exists stations_service_source_uidx;
alter table stations add constraint stations_service_source_uidx unique (service_id, source_id);

