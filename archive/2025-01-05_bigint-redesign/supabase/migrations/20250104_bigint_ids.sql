-- 3) Timeseries station mapping: convert station_id to bigint
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_name = 'timeseries' and column_name = 'station_id' and data_type = 'text'
  ) then
    execute 'alter table timeseries rename column station_id to station_source_id';
  end if;
  if not exists (
    select 1 from information_schema.columns
    where table_name = 'timeseries' and column_name = 'station_id'
  ) then
    execute 'alter table timeseries add column station_id bigint';
  end if;
end $$;

update timeseries ts
set station_id = stn.id
from stations stn
where ts.station_id is null
  and ts.station_source_id is not null
  and stn.service_id = ts.service_id
  and stn.source_id = ts.station_source_id;

alter table timeseries drop constraint if exists timeseries_station_id_fkey;
alter table timeseries add constraint timeseries_station_id_fkey
  foreign key (station_id) references stations(id) on delete cascade;

