-- 4) Reference values: switch timeseries_id to bigint
alter table reference_values add column if not exists timeseries_id_bigint bigint;
update reference_values rv
set timeseries_id_bigint = ts.id
from timeseries ts
where rv.timeseries_id_bigint is null
  and rv.timeseries_id::text = ts.source_id;

alter table reference_values drop constraint if exists reference_values_timeseries_id_fkey;
alter table reference_values drop column if exists timeseries_id;
alter table reference_values rename column timeseries_id_bigint to timeseries_id;
alter table reference_values add constraint reference_values_timeseries_id_fkey
  foreign key (timeseries_id) references timeseries(id) on delete cascade;

-- 5) Observations: switch timeseries_id to bigint and primary key
alter table observations add column if not exists timeseries_id_bigint bigint;
update observations obs
set timeseries_id_bigint = ts.id
from timeseries ts
where obs.timeseries_id_bigint is null
  and obs.timeseries_id::text = ts.source_id;

alter table observations drop constraint if exists observations_pkey;
alter table observations drop column if exists timeseries_id;
alter table observations rename column timeseries_id_bigint to timeseries_id;
alter table observations alter column timeseries_id set not null;
alter table observations add constraint observations_pkey primary key (timeseries_id, observed_at);
alter table observations add constraint observations_timeseries_fkey
  foreign key (timeseries_id) references timeseries(id) on delete cascade;
