-- UK Air Quality schema (bigint IDs + external *_ref fields)
-- External identifiers that arrive as text (even if numeric) use *_ref.
-- Internal joins always use bigint *_id columns.
-- Safe to rerun; uses IF NOT EXISTS where appropriate.

-- Ensure needed extensions
create extension if not exists postgis;
create extension if not exists pgcrypto;

-- Services (external data sources)
create table if not exists services (
  id bigint generated by default as identity primary key,
  service_ref text not null,
  label text not null,
  service_url text,
  poll_enabled boolean default true,
  poll_interval_minutes int default 60,
  poll_window_hours int default 6,
  poll_timeseries_batch_size int,
  stations_bbox_supported boolean default true,
  timeseries_station_filter_supported boolean default true,
  last_polled_at timestamptz,
  created_at timestamptz default now()
);
create unique index if not exists services_service_ref_uidx on services(service_ref);

-- Default flags for known services (applies on insert; update existing rows if present).
create or replace function services_apply_known_defaults()
returns trigger as $$
begin
  if new.service_url = 'https://uk-air.defra.gov.uk/sos-ukair/api/v1'
     or new.label = 'UK-AIR-SOS' then
    new.stations_bbox_supported = false;
    new.timeseries_station_filter_supported = false;
  end if;
  return new;
end;
$$ language plpgsql;

drop trigger if exists services_apply_known_defaults on services;
create trigger services_apply_known_defaults
before insert on services
for each row execute function services_apply_known_defaults();

update services
set stations_bbox_supported = false,
    timeseries_station_filter_supported = false,
    poll_timeseries_batch_size = null
where service_url = 'https://uk-air.defra.gov.uk/sos-ukair/api/v1'
   or label = 'UK-AIR-SOS';

