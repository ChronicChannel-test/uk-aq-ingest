-- Default flags for known services (applies on insert; update existing rows if present).
create or replace function services_apply_known_defaults()
returns trigger
set search_path = public, pg_catalog
as $$
begin
  if new.service_url = 'https://uk-air.defra.gov.uk/sos-ukair/api/v1'
     or new.label = 'UK-AIR-SOS' then
    new.stations_bbox_supported = false;
    new.timeseries_station_filter_supported = false;
  end if;
  return new;
end;
$$ language plpgsql;

drop trigger if exists services_apply_known_defaults on services;
create trigger services_apply_known_defaults
before insert on services
for each row execute function services_apply_known_defaults();

update services
set stations_bbox_supported = false,
    timeseries_station_filter_supported = false,
    poll_timeseries_batch_size = null
where service_url = 'https://uk-air.defra.gov.uk/sos-ukair/api/v1'
   or label = 'UK-AIR-SOS';

